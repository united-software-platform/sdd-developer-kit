#!/bin/sh
# Проверка ссылочной целостности документации репозитория SDD Developer Kit.
#
# Ищет два вида дефектов:
#   1. относительную ссылку на путь, которого в репозитории нет;
#   2. код правила вида READ-008 или DOC-042, которому не соответствует ни одно правило в rules/.
#
# Область проверки — документация репозитория: README.md, CLAUDE.md, AGENTS.md, CONTRIBUTING.md,
# rules/ и README-файлы каталогов tools/. Артефакты процесса openspec/ не проверяются: proposal
# описывает состояние после применения изменения, архив — состояние на момент архивации, и оба
# законно ссылаются на файлы, которых в рабочем дереве сейчас нет.
#
# Раздел «## Версионирование» до конца файла из проверки кодов исключён: таблица версий описывает
# историю и законно упоминает удалённые правила — она не действующая норма, а её описание.
#
# Из проверки исключены и три вида фрагментов, где совпадение заведомо ложное:
#   - блоки кода ``` — там живут образцы сообщений коммитов (USP-001) и шаблоны ссылок
#     (./path/file.md), то есть примеры формата, а не действующие ссылки и коды;
#   - фрагменты в обратных кавычках — та же причина в пределах строки;
#   - адреса внутри круглых скобок ссылки — их содержимое проверяется как путь, но кодом правила
#     быть не может: цвет бейджа license-MIT-007EC6 иначе читался бы как код MIT-007.
#
# Скрипт вызывается локально до отправки изменений и из пайплайна GitHub Actions — вердикт
# в обоих случаях один и тот же. В состав поставки скрипт не входит: установленный проект ведёт
# свою документацию по собственным правилам.

set -eu

SELF=$(basename "$0")
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/../.." && pwd)

usage() {
    cat <<'USAGE'
Использование: check.sh [ОПЦИИ]

Проверяет ссылочную целостность документации репозитория: относительные ссылки указывают
на существующие пути, а коды правил имеют определение в rules/.

Опции:
  -h, --help   эта справка

Коды возврата: 0 — нарушений нет, 1 — нарушения найдены, 2 — ошибка вызова или окружения.
USAGE
}

die() {
    printf '%s: %s\n' "$SELF" "$1" >&2
    exit "${2:-2}"
}

while [ $# -gt 0 ]; do
    case "$1" in
        -h|--help) usage; exit 0 ;;
        *) die "неизвестный аргумент: $1 (см. $SELF --help)" ;;
    esac
done

[ -d "$ROOT/rules" ] || die "каталог правил не найден: $ROOT/rules"

cd "$ROOT"

# --- Перечень проверяемых файлов ---------------------------------------------
# Список собирается явно, а не обходом всего дерева: область проверки — документация
# репозитория, и расширять её молча нежелательно.
FILES=$(
    for candidate in README.md CLAUDE.md AGENTS.md CONTRIBUTING.md; do
        [ -f "$candidate" ] && printf '%s\n' "$candidate"
    done
    find rules -name '*.md' -type f 2>/dev/null | sort
    find tools -name 'README.md' -type f 2>/dev/null | sort
)

[ -n "$FILES" ] || die "не найдено ни одного файла документации"

# --- Определённые коды правил ------------------------------------------------
# Код считается определённым, если он встречается в таблице правил документа rules/ в первой
# колонке строки таблицы: именно она объявляет правило, остальные упоминания — ссылки на него.
DEFINED=$(grep -hoE '^\| [A-Z]{3,6}-[0-9]{3} ' rules/*.md 2>/dev/null \
    | tr -d '| ' | sort -u)

[ -n "$DEFINED" ] || die "в rules/ не найдено ни одного определения правила"

STATUS=0

report() {
    printf '%s:%s: %s\n' "$1" "$2" "$3"
    STATUS=1
}

for file in $FILES; do
    dir=$(dirname "$file")
    line_no=0
    in_versions=0
    in_fence=0

    while IFS= read -r line; do
        line_no=$((line_no + 1))

        # Раздел версий и всё после него из проверки кодов исключаются
        case "$line" in
            '## Версионирование'*) in_versions=1 ;;
        esac

        # Блок кода целиком вне проверки: открывающая и закрывающая рамки тоже
        case "$line" in
            '```'*|'````'*)
                in_fence=$((1 - in_fence))
                continue ;;
        esac
        [ "$in_fence" -eq 1 ] && continue

        # Фрагменты в обратных кавычках вырезаются: внутри них живут образцы формата
        line=$(printf '%s\n' "$line" | sed 's/`[^`]*`/ /g')

        # --- Относительные ссылки ---
        # Из строки вынимаются цели вида ](./path) и ](../path); якорь отбрасывается,
        # внешние адреса и внутристраничные якоря не проверяются.
        targets=$(printf '%s\n' "$line" \
            | grep -oE '\]\(\.\.?/[^) ]+\)' 2>/dev/null \
            | sed 's/^](//; s/)$//; s/#.*$//' || true)
        for target in $targets; do
            [ -n "$target" ] || continue
            if [ ! -e "$dir/$target" ]; then
                report "$file" "$line_no" "ссылка на несуществующий путь: $target"
            fi
        done

        # --- Коды правил ---
        [ "$in_versions" -eq 1 ] && continue
        # Адреса ссылок вырезаются: путь уже проверен выше, а кодом правила адрес быть не может
        codes=$(printf '%s\n' "$line" | sed 's/](\([^)]*\))/] /g' \
            | grep -oE '[A-Z]{3,6}-[0-9]{3}' 2>/dev/null || true)
        for code in $codes; do
            if ! printf '%s\n' "$DEFINED" | grep -qx "$code"; then
                report "$file" "$line_no" "код правила без определения в rules/: $code"
            fi
        done
    done < "$file"
done

if [ "$STATUS" -eq 0 ]; then
    printf 'Проверка ссылочной целостности пройдена: файлов — %s.\n' "$(printf '%s\n' "$FILES" | wc -l | tr -d ' ')"
else
    printf '\nПроверка ссылочной целостности не пройдена: см. перечень выше.\n' >&2
fi

exit "$STATUS"
